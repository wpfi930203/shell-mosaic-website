export function getManagedPage(pages: ManagedPage[], slug: string) {
  return pages.find((page) => page.slug === slug);
}

export function getPageBlock(pages: ManagedPage[], slug: string, blockId: string) {
  const page = getManagedPage(pages, slug);
  return page?.blocks.find((block) => block.id === blockId);
}
