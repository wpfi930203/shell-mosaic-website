export function t(locale: LocaleCode, key: keyof (typeof ui)["en"]) {
  return ui[locale][key] ?? ui.en[key];
}

export function formatUiText(
  locale: LocaleCode,
  key: keyof (typeof ui)["en"],
  replacements: Record<string, string>,
) {
  return Object.entries(replacements).reduce(
    (text, [placeholder, value]) => text.replaceAll(`{${placeholder}}`, value),
    t(locale, key),
  );
}

export function getLocalizedText(
  base: string,
  translations: LocalizedText | undefined,
  locale: LocaleCode,
) {
  return translations?.[locale] ?? fallbackTextMap[base]?.[locale] ?? base;
}

export function localizeSimpleText(base: string, locale: LocaleCode) {
  return getLocalizedText(base, undefined, locale);
}

export function localizeSiteStoreName(settings: SiteSettings, locale: LocaleCode) {
  return getLocalizedText(settings.storeName, settings.storeNameTranslations, locale);
}

export function localizeMenuItem(item: MenuItem, locale: LocaleCode) {
  return getLocalizedText(item.label, item.labelTranslations, locale);
}

export function localizeFooterSection(section: FooterSection, locale: LocaleCode) {
  return {
    ...section,
    title: getLocalizedText(section.title, section.titleTranslations, locale),
    links: section.links.map((link) => ({
      ...link,
      label: getLocalizedText(link.label, link.labelTranslations, locale),
    })),
  };
}

export function localizeFilterGroup(group: FilterGroup, locale: LocaleCode) {
  return {
    ...group,
    label: getLocalizedText(group.label, group.labelTranslations, locale),
    options: group.options.map((option) => ({
      ...option,
      label: getLocalizedText(option.label, option.labelTranslations, locale),
    })),
  };
}

